# All 7 types of operators in python 

# 1. Arithmetic Operators 

# + addition
print(2+3)#5

# - subtraction
print(2-3)#-1

# * multiplication
print(2*3)#6

# / always returns float value

print(2/3)#0.6666666666666666

# % modulo operator
print(2%3)#2

# ** exponentiation operator
print(2**3)#8

# // returns integer value
print(2//3)#0

#2. Assignment Operators

# = assignment
x = 5
print(x)#5

# += addition assignment
x += 3
print(x)#8

# -= subtraction assignment
x -= 3
print(x)#5

# *= multiplication assignment
x *= 3
print(x)#15

# /= division assignment
x /= 3
print(x)#5.0

#3. Comparison Operators 

# == equal to
print(2 == 3)#False

# != not equal to
print(2 != 3)#True

# < less than
print(2 < 3)#True

# > greater than
print(2 > 3)#False

# <= less than or equal to
print(2 <= 3)#True

# >= greater than or equal to
print(2 >= 3)#False